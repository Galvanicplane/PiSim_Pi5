#!/usr/bin/env python3
"""
PiSim <-> ArduPilot SITL Multi-Vehicle Bridge (ardupilot_sitl_bridge.py)

Implements the Unreal <-> ArduPilot SITL bridge architecture (PiSim-Description.pdf pp. 2-3):
1. Receives all sensor messages emitted by Unreal on single UDP port 7500 (or Zenoh pisim/<vehicle>/*).
2. Aggregates sensors per vehicle (`vehicle_1`, `vehicle_2`, ...) and feeds each vehicle's ArduPilot
   SITL instance at regular intervals (50 Hz FDM / JSON state packets).
3. Exports & synchronizes per-vehicle channel-to-motor `.param` definitions (`SERVO1_FUNCTION`, ...).
4. Subscribes to MAVLink command topics from controller devices on the Zenoh mesh
   (`pisim/<vehicle>/mavlink_tx` - light green arrow) and forwards them to ArduPilot SITL,
   publishing SITL MAVLink telemetry back to `pisim/<vehicle>/mavlink_rx`.
5. Converts ArduPilot SITL servo PWM outputs (1000..2000 us) into PiSim channel commands (-1.0..+1.0)
   and forwards them as Binary CDR to Zenoh and JSON UDP to Unreal's single command port 7402.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import socket
import struct
import threading
import time
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from ros2_cdr import serialize_channels_cdr, deserialize_imu_cdr, deserialize_gps_cdr

try:
    import zenoh  # type: ignore
    HAS_ZENOH = True
except ImportError:
    zenoh = None
    HAS_ZENOH = False


@dataclass
class VehicleSitlState:
    """Aggregated sensor + SITL state for one simulated vehicle."""
    vehicle_code: str
    vehicle_index: int = 1
    sitl_host: str = "127.0.0.1"
    sitl_fdm_port: int = 9002
    sitl_mavlink_port: int = 14550
    lat: float = 0.0
    lon: float = 0.0
    alt: float = 0.0
    speed_kmh: float = 0.0
    roll_deg: float = 0.0
    pitch_deg: float = 0.0
    yaw_deg: float = 0.0
    imu_accel: List[float] = field(default_factory=lambda: [0.0, 0.0, -9.81])
    imu_gyro: List[float] = field(default_factory=lambda: [0.0, 0.0, 0.0])
    baro_hpa: float = 1013.25
    channel_map: Dict[str, Dict[str, Any]] = field(default_factory=dict)
    pwm_channels: List[int] = field(default_factory=lambda: [1500] * 16)
    last_sensor_ts: float = 0.0
    last_sitl_tx_ts: float = 0.0
    mavlink_rx_count: int = 0
    mavlink_tx_count: int = 0

    def to_ardupilot_json_fdm(self) -> Dict[str, Any]:
        """Build ArduPilot JSON-backend FDM state packet."""
        return {
            "timestamp": time.time(),
            "imu": {
                "gyro": self.imu_gyro,
                "accel_body": self.imu_accel,
            },
            "position": [self.lat, self.lon, self.alt],
            "attitude": [
                math.radians(self.roll_deg),
                math.radians(self.pitch_deg),
                math.radians(self.yaw_deg),
            ],
            "velocity": [self.speed_kmh / 3.6, 0.0, 0.0],
        }

    def generate_param_text(self) -> str:
        """Generate ArduPilot `.param` lines from the vehicle's channel-to-motor definition."""
        lines = [
            f"# Auto-generated by pisim ardupilot_sitl_bridge.py for {self.vehicle_code}",
            f"SYSID_THISMAV,{max(1, self.vehicle_index)}",
        ]
        if not self.channel_map:
            lines.append("SERVO1_FUNCTION,70  # Drive Wheels (CH1)")
            lines.append("SERVO2_FUNCTION,26  # Ground Steering Servo (CH2)")
            lines.append("SERVO3_FUNCTION,73  # Throttle / Propeller (CH3)")
        else:
            for ch_str, meta in sorted(self.channel_map.items(), key=lambda kv: int(kv[0]) if str(kv[0]).isdigit() else 99):
                func_id = int(meta.get("servo_function", 0))
                mod_type = meta.get("module_type", "Unknown")
                bone = meta.get("bone", "")
                lines.append(f"SERVO{ch_str}_FUNCTION,{func_id}  # {mod_type} ({bone})")
        return "\n".join(lines) + "\n"

    def pwm_to_normalized_channels(self) -> Dict[str, float]:
        """Convert 16 ArduPilot PWM channels (1000..2000 us) into PiSim [-1.0..+1.0] channel dict."""
        ch_dict: Dict[str, float] = {}
        for idx, pwm in enumerate(self.pwm_channels, start=1):
            norm = max(-1.0, min(1.0, (pwm - 1500.0) / 500.0))
            if abs(norm) > 0.002 or idx <= 4:
                ch_dict[str(idx)] = round(norm, 4)
        return ch_dict


class ArduPilotSitlBridge:
    """Central multi-vehicle Unreal <-> ArduPilot SITL <-> Zenoh MAVLink bridge."""

    def __init__(
        self,
        sensor_listen_port: int = 7505,
        unreal_cmd_host: str = "127.0.0.1",
        unreal_cmd_port: int = 7402,
        sitl_base_fdm_port: int = 9002,
        sitl_rate_hz: float = 50.0,
        enable_zenoh: bool = True,
    ):
        self.sensor_listen_port = sensor_listen_port
        self.unreal_cmd_host = unreal_cmd_host
        self.unreal_cmd_port = unreal_cmd_port
        self.sitl_base_fdm_port = sitl_base_fdm_port
        self.sitl_rate_hz = sitl_rate_hz
        self.enable_zenoh = enable_zenoh and HAS_ZENOH

        self.vehicles: Dict[str, VehicleSitlState] = {}
        self.lock = threading.RLock()
        self.running = False

        self.rx_sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.rx_sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.tx_sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)

        self.zenoh_session = None

    def get_or_create_vehicle(self, vehicle_code: str, vehicle_id: int = 0) -> VehicleSitlState:
        with self.lock:
            if vehicle_code not in self.vehicles:
                idx = vehicle_id if vehicle_id > 0 else (len(self.vehicles) + 1)
                self.vehicles[vehicle_code] = VehicleSitlState(
                    vehicle_code=vehicle_code,
                    vehicle_index=idx,
                    sitl_fdm_port=self.sitl_base_fdm_port + (idx - 1) * 10,
                    sitl_mavlink_port=14550 + (idx - 1) * 10,
                )
            return self.vehicles[vehicle_code]

    def ingest_sensor_packet(self, pkt: Dict[str, Any]) -> Optional[VehicleSitlState]:
        """Aggregate a sensor or param packet coming from Unreal into the vehicle's state."""
        vcode = str(pkt.get("vehicle") or "").strip()
        topic = str(pkt.get("topic") or "")
        if not vcode and topic:
            parts = [p for p in topic.strip("/").split("/") if p]
            if len(parts) >= 2 and parts[0] == "pisim":
                vcode = parts[1]
            elif parts:
                vcode = parts[0]
        if not vcode:
            return None

        vid = int(pkt.get("vehicle_id", 0) or 0)
        v = self.get_or_create_vehicle(vcode, vid)
        ptype = str(pkt.get("type") or "").lower()

        with self.lock:
            v.last_sensor_ts = time.time()
            if ptype == "sitl_param_def" or "channel_map" in pkt:
                v.channel_map = dict(pkt.get("channel_map", {}))
            if "lat" in pkt:
                v.lat = float(pkt.get("lat", v.lat))
                v.lon = float(pkt.get("lon", v.lon))
                v.alt = float(pkt.get("alt", v.alt))
            if "speed_kmh" in pkt:
                v.speed_kmh = float(pkt.get("speed_kmh", v.speed_kmh))
            if "imu_accel" in pkt and isinstance(pkt["imu_accel"], list):
                v.imu_accel = [float(x) for x in pkt["imu_accel"][:3]]
            if "imu_gyro" in pkt and isinstance(pkt["imu_gyro"], list):
                v.imu_gyro = [float(x) for x in pkt["imu_gyro"][:3]]
            if "roll_deg" in pkt:
                v.roll_deg = float(pkt.get("roll_deg", v.roll_deg))
                v.pitch_deg = float(pkt.get("pitch_deg", v.pitch_deg))
                v.yaw_deg = float(pkt.get("yaw_deg", v.yaw_deg))
            if "baro_hpa" in pkt:
                v.baro_hpa = float(pkt.get("baro_hpa", v.baro_hpa))

            # Support standard topic envelopes (`topic: "/<vehicle>/imu"`, `topic: "/<vehicle>/gps"`)
            msg = pkt.get("msg", pkt)
            if topic.endswith("/gps"):
                v.lat = float(msg.get("latitude", msg.get("lat", v.lat)))
                v.lon = float(msg.get("longitude", msg.get("lon", v.lon)))
                v.alt = float(msg.get("altitude", msg.get("alt", v.alt)))
            elif topic.endswith("/imu"):
                ang = msg.get("angular_velocity", {})
                lin = msg.get("linear_acceleration", {})
                if isinstance(ang, dict):
                    v.imu_gyro = [float(ang.get("x", 0.0)), float(ang.get("y", 0.0)), float(ang.get("z", 0.0))]
                if isinstance(lin, dict):
                    v.imu_accel = [float(lin.get("x", 0.0)), float(lin.get("y", 0.0)), float(lin.get("z", -9.81))]
        return v

    def handle_mavlink_command(self, vehicle_code: str, payload: bytes) -> bool:
        """Forward MAVLink commands received from Zenoh controller devices to ArduPilot SITL."""
        v = self.get_or_create_vehicle(vehicle_code)
        try:
            self.tx_sock.sendto(payload, (v.sitl_host, v.sitl_mavlink_port))
            with self.lock:
                v.mavlink_rx_count += 1
            return True
        except Exception:
            return False

    def dispatch_sitl_servo_outputs(self, vehicle_code: str, pwm_list: List[int]) -> Dict[str, Any]:
        """Forward raw ArduPilot SITL 1000..2000 us PWM outputs untouched -> Unreal (7402) & Zenoh."""
        v = self.get_or_create_vehicle(vehicle_code)
        with self.lock:
            for i in range(min(16, len(pwm_list))):
                v.pwm_channels[i] = int(pwm_list[i])
            raw_pwm_map = {str(idx + 1): int(v.pwm_channels[idx]) for idx in range(min(8, len(v.pwm_channels)))}
            raw_pwm_list = [int(x) for x in v.pwm_channels[:8]]

        ue_pkt = {
            "cmd": "ardupilot_pwm",
            "target": vehicle_code,
            "topic": f"/{vehicle_code}/ardupilot/pwm",
            "channels": raw_pwm_map,
            "pwm": raw_pwm_list,
            "source": "ardupilot_sitl",
        }
        raw_json = json.dumps(ue_pkt).encode("utf-8")
        try:
            self.tx_sock.sendto(raw_json, (self.unreal_cmd_host, self.unreal_cmd_port))
        except Exception:
            pass

        if self.zenoh_session is not None:
            try:
                cdr_bytes = serialize_channels_cdr(raw_pwm_map)
                self.zenoh_session.put(f"pisim/{vehicle_code}/ardupilot/pwm", cdr_bytes)
            except Exception:
                pass
        return ue_pkt

    def _udp_sensor_loop(self) -> None:
        self.rx_sock.bind(("0.0.0.0", self.sensor_listen_port))
        self.rx_sock.settimeout(0.25)
        while self.running:
            try:
                data, _ = self.rx_sock.recvfrom(65535)
                pkt = json.loads(data.decode("utf-8", errors="replace"))
                self.ingest_sensor_packet(pkt)
            except socket.timeout:
                continue
            except Exception:
                continue

    def _sitl_feeder_loop(self) -> None:
        period = 1.0 / max(1.0, self.sitl_rate_hz)
        while self.running:
            t0 = time.time()
            with self.lock:
                items = list(self.vehicles.values())
            for v in items:
                try:
                    fdm_pkt = json.dumps(v.to_ardupilot_json_fdm()).encode("utf-8")
                    self.tx_sock.sendto(fdm_pkt, (v.sitl_host, v.sitl_fdm_port))
                    v.last_sitl_tx_ts = time.time()
                except Exception:
                    pass
            elapsed = time.time() - t0
            if elapsed < period:
                time.sleep(period - elapsed)

    def _setup_zenoh(self) -> None:
        if not self.enable_zenoh:
            return
        try:
            cfg = zenoh.Config()
            self.zenoh_session = zenoh.open(cfg)

            def _on_mavlink_tx(sample: Any) -> None:
                key = str(sample.key_expr)
                parts = key.split("/")
                if len(parts) >= 3 and parts[0] == "pisim":
                    self.handle_mavlink_command(parts[1], bytes(sample.payload))

            self.zenoh_session.declare_subscriber("pisim/*/mavlink_tx", _on_mavlink_tx)
        except Exception as exc:
            print(f"[ArduPilotSitlBridge] Zenoh init skipped: {exc}")
            self.zenoh_session = None

    def start(self) -> None:
        self.running = True
        self._setup_zenoh()
        threading.Thread(target=self._udp_sensor_loop, daemon=True).start()
        threading.Thread(target=self._sitl_feeder_loop, daemon=True).start()
        print(f"[ArduPilotSitlBridge] Running (UDP sensor port={self.sensor_listen_port} -> Unreal cmd={self.unreal_cmd_port}, Zenoh={self.zenoh_session is not None})")

    def stop(self) -> None:
        self.running = False
        try:
            self.rx_sock.close()
            self.tx_sock.close()
        except Exception:
            pass
        if self.zenoh_session is not None:
            try:
                self.zenoh_session.close()
            except Exception:
                pass


def main() -> None:
    parser = argparse.ArgumentParser(description="PiSim Multi-Vehicle ArduPilot SITL Bridge")
    parser.add_argument("--sensor-port", type=int, default=7505)
    parser.add_argument("--unreal-port", type=int, default=7402)
    parser.add_argument("--sitl-base-port", type=int, default=9002)
    parser.add_argument("--rate", type=float, default=50.0)
    args = parser.parse_args()

    bridge = ArduPilotSitlBridge(
        sensor_listen_port=args.sensor_port,
        unreal_cmd_port=args.unreal_port,
        sitl_base_fdm_port=args.sitl_base_port,
        sitl_rate_hz=args.rate,
    )
    bridge.start()
    try:
        while True:
            time.sleep(1.0)
    except KeyboardInterrupt:
        bridge.stop()


if __name__ == "__main__":
    main()
